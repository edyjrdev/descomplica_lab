CREATE TABLE VENDEDOR (
    cod INTEGER PRIMARY KEY UNIQUE,
    nome CHARACTER,
    endereco CHARACTER,
    percentual_comiss DECIMAL
);

CREATE TABLE CLIENTE (
    cod INTEGER PRIMARY KEY UNIQUE,
    nome CHARACTER,
    endereco CHARACTER,
    faturamento_acum DECIMAL,
    limite_credito DECIMAL
);

CREATE TABLE PEDIDO (
    cod INTEGER PRIMARY KEY UNIQUE,
    data_pedido DATE,
    cod_cli INTEGER,
    cod_vend INTEGER
);

CREATE TABLE PECA (
    cod INTEGER PRIMARY KEY UNIQUE,
    descricao CHARACTER,
    preco_unit DECIMAL
);

CREATE TABLE DEPOSITO (
    cod INTEGER PRIMARY KEY UNIQUE,
    endereco CHARACTER
);

CREATE TABLE PEDIDO_ITEM (
    cod INTEGER PRIMARY KEY,
    cod_peca INTEGER,
    qtd_peca INTEGER,
    cod_pedido INTEGER,
    UNIQUE (cod, cod_pedido)
);

CREATE TABLE PECA_DEPOSITO (
    cod_peca INTEGER,
    cod_dep INTEGER,
    qtd INTEGER,
    PRIMARY KEY (cod_dep, cod_peca),
    UNIQUE (cod_peca, cod_dep)
);
 
